const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises'),path=require('node:path');
const BASE=process.env.BASE_URL||'http://localhost:4173';
(async()=>{
 const {MODELS}=await import('../server/studio-core.mjs');
 const {CREDIT_PLANS,PRICING_VERSION,formatINR}=await import('../apps/studio/pricing.js');
 const browser=await chromium.launch(),context=await browser.newContext({viewport:{width:1440,height:1000}});
 let submissions=0;const errors=[];
 await context.route('**/api/cloud',r=>r.fulfill({contentType:'application/json',body:'{"enabled":false}'}));
 await context.route('**/api/studio**',r=>{
  if(r.request().method()!=='GET'){submissions++;throw Error('Signed-out quote must not submit a provider request');}
  return r.fulfill({contentType:'application/json',body:JSON.stringify({models:MODELS,sharedProviderConfigured:false})});
 });
 await context.route('**/api/billing**',r=>r.fulfill({contentType:'application/json',body:JSON.stringify({enabled:false,generationEnabled:true,usdInr:100,fxDate:'2026-10-10',pricingVersion:PRICING_VERSION,hostedModels:['flux-fast','nano-banana','nano-edit','kling'],plans:CREDIT_PLANS.map(p=>({...p,available:false}))})}));
 const page=await context.newPage();page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(BASE+'/apps/#create-video');await page.locator('#generation-model').waitFor();
 await page.locator('#generation-model').selectOption('kling');
 const expectQuote=async amount=>{const label=formatINR(amount);await page.waitForFunction(s=>document.querySelector('#model-hint')?.textContent.startsWith(s),label);assert.ok((await page.locator('#generate').textContent()).includes(label));};
 await expectQuote(42);await page.locator('#advanced-toggle').click();
 await page.locator('#generation-audio').check();await expectQuote(84);
 await page.locator('#generation-duration').selectOption('10');await expectQuote(168);
 assert.ok((await page.locator('#model-hint').textContent()).includes('168 credits'));
 await page.goto(BASE+'/creative-studio-pricing');
 await page.locator('#fal-prices').waitFor();
 assert.equal(await page.locator('#fal-prices tbody tr').count(),74);
 await page.locator('[data-price-search-input]').fill('seedance');
 assert.equal(await page.locator('#fal-prices tbody tr:visible').count(),2);
 assert.ok((await page.locator('#fal-prices tbody').textContent()).includes('$0.312'));
 await page.locator('[data-example-cost]').fill('200');
 assert.ok((await page.locator('[data-example-result]').textContent()).includes('240 credits'));
 assert.ok((await page.locator('[data-example-result]').textContent()).includes('760 credits'));
 await page.locator('[data-example-balance]').fill('100');
 assert.ok((await page.locator('[data-example-result]').textContent()).includes('Insufficient balance'));
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Price catalog must fit mobile');
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(BASE+'/apps/#create-image');await page.locator('#generation-model').selectOption('nano-banana');
 await expectQuote(9.6);await page.locator('#advanced-toggle').click();
 await page.locator('#generation-resolution').selectOption('4K');await expectQuote(19.2);
 await page.locator('#generation-count').selectOption('4');await expectQuote(76.8);
 await page.locator('#generation-model').selectOption('flux-2');
 assert.ok((await page.locator('#model-hint').textContent()).includes('planned'));
 assert.equal(await page.locator('#generate').isDisabled(),true,'Unpriced model must remain planned');
 await page.locator('#generation-model').selectOption('nano-banana');
 await page.locator('#generation-prompt').fill('A garden');await page.locator('#generate').click();
 await page.waitForURL('**/#account');assert.equal(submissions,0);
 assert.equal(errors.length,0,errors.join('\n'));
 const output=path.join(__dirname,'results/creative-apps/pricing');await fs.mkdir(output,{recursive:true});
 await fs.writeFile(path.join(output,'verification.json'),JSON.stringify({videoDurationAndAudio:true,imageResolutionAndBatch:true,unpricedModelsPlanned:true,signedOutSubmissionBlocked:true,providerRequests:submissions,errors},null,2));
 await browser.close();console.log('PASS composer INR prices, planned-model restriction and signed-out generation guard (config mocked).');
})().catch(e=>{console.error(e);process.exit(1);});
